    ('한예진', '간호과', '20260122'), ('오세훈', '경영과', '20260123'), ('오세운', '유아교육과', '20260124'),
    ('서지민', '호텔조리과', '20260125'), ('서지면', '국제처', '20260126'),
    ('신가은', '관광과', '20260127'), ('신가온', '관광과', '20260127'),  # 진짜 오류 의심: 같은 학번인데 이름이 한 글자 다름
