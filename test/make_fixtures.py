# 이름이 많은 파일이라도 이름이 아닌 말의 진짜 오타는 계속 잡아야 함
ws.cell(row=32, column=1).value = '비고: 11.3. 설망회 참석자 명단, 취업율·이직율 조사 함께 진행'
wb.save(out('02_방문자명단.xlsx'))

# 3. 예산 내역(학생 명단 아님): 빈칸, 한 줄 안 계산(참가비 − 장학금 = 본인부담) 한 줄 틀림, 앞뒤 공백 많이
