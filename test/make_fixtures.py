    ('강지우', '호텔조리과', '20260113'), ('강지유', '국제처', '20260114'), ('윤채원', '관광과', '20260115'),
    ('윤채윤', '간호과', '20260116'), ('장도윤', '경영과', '20260117'), ('장도연', '유아교육과', '20260118'),
