# MK4.2 검증용 가짜 파일 만들기 (실제 학생·직원 정보 없음, 이름·번호는 모두 지어낸 것)
# 실행: python test/make_fixtures.py  → test/ 폴더에 엑셀·워드 파일 4개가 생김
import os
from openpyxl import Workbook
from docx import Document

HERE = os.path.dirname(os.path.abspath(__file__))
out = lambda n: os.path.join(HERE, n)

# 1. 합계 검사: 인원 칸이 금액 칸 왼쪽에 붙은 표(오탐 사례) + 진짜 틀린 합계 한 줄
wb = Workbook(); ws = wb.active; ws.title = '예산'
ws.append(['구분', '방문 인원', '교비', '혁신', '계'])
ws.append(['해외 대학 방문', 528, 10000000, 8500000, 18500000])
ws.append(['국내 연수', 42, 3000000, 1200000, 4200000])
ws.append(['홍보 행사', 130, 2500000, 500000, 3000000])
ws.append(['간담회', 25, 800000, 400000, 1300000])  # 진짜 오류: 800,000 + 400,000 = 1,200,000
ws.append(['합계', 725, 16300000, 10600000, 27000000])
# 머리글에 인원이란 말이 없는 작은 숫자 칸(오탐 사례의 다른 꼴): 빼면 정확히 맞으니 오류로 안 봄
ws2 = wb.create_sheet('방문')
ws2.append(['구분', '방문', '교비', '혁신', '계'])
ws2.append(['대학 A', 37, 2000000, 1500000, 3500000])
ws2.append(['대학 B', 19, 1000000, 700000, 1700000])
ws2.append(['대학 C', 8, 600000, 300000, 900000])
# 진짜 오류는 계속 잡아야 함: 1월 5,000원을 빠뜨린 합계(작은 금액이라도), 사람 수끼리 더한 합계가 틀림
ws3 = wb.create_sheet('월별')
ws3.append(['항목', '1월', '2월', '3월', '계'])
ws3.append(['소모품', 5000, 300000, 400000, 700000])  # 진짜 오류: 705,000
ws3.append(['인쇄비', 120000, 80000, 50000, 250000])
ws4 = wb.create_sheet('성별')
ws4.append(['학과', '남(명)', '여(명)', '계'])
ws4.append(['관광과', 12, 18, 30])
ws4.append(['간호과', 5, 40, 44])  # 진짜 오류: 45
ws4.append(['경영과', 20, 15, 35])
wb.save(out('01_합계_인원열.xlsx'))

