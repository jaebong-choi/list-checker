    ('이유진', '국제처', '20260101'), ('이의진', '관광과', '20260102'), ('김경희', '간호과', '20260103'),
    ('김공희', '유아교육과', '20260104'), ('황보은률', '경영과', '20260105'), ('김은률', '호텔조리과', '20260106'),
    ('박서준', '국제처', '20260107'), ('박서준', '컴퓨터과', '20260108'), ('최민서', '관광과', '20260109'),
